import com.bank.service.CustomerService;
import com.bank.service.CustomerServiceImpl;

import java.util.InputMismatchException;
import java.util.List;
import java.util.Scanner;

public class App {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        CustomerService service = new CustomerServiceImpl();

        try {
            while (true) {
                System.out.println("\n===== CUSTOMER MANAGEMENT SYSTEM =====");
                System.out.println("1. Add Customer");
                System.out.println("2. View Customers");
                System.out.println("3. Update Customer");
                System.out.println("4. Delete Customer");
                System.out.println("5. Exit");
                System.out.print("Enter choice: ");

                int choice;
                try {
                    choice = sc.nextInt();
                    sc.nextLine(); 
                } catch (InputMismatchException e) {
                    System.out.println("❌ Invalid input! Please enter a number (1-5).");
                    sc.nextLine();
                    continue;
                }

                try {
                    switch (choice) {
                        case 1:
                            System.out.print("Name: ");
                            String name = sc.nextLine().trim();
                            System.out.print("Email: ");
                            String email = sc.nextLine().trim();
                            System.out.print("Phone: ");
                            String phone = sc.nextLine().trim();

                            validateInput(name, email, phone);

                            Customer newCustomer = new Customer(name, email, phone);
                            Customer added = service.addCustomer(newCustomer);
                            System.out.println("✅ Customer added: " + added);
                            break;

                        case 2:
                            List<Customer> customers = service.getCustomers();
                            if (customers.isEmpty()) {
                                System.out.println("ℹ️ No customers found.");
                            } else {
                                customers.forEach(System.out::println);
                            }
                            break;

                        case 3:
                            System.out.print("Enter Customer ID: ");
                            int id = sc.nextInt();
                            sc.nextLine();
                            System.out.print("Enter new Email: ");
                            String newEmail = sc.nextLine().trim();
                            System.out.print("Enter new Phone: ");
                            String newPhone = sc.nextLine().trim();

                            validateInput("dummy", newEmail, newPhone);

                            Customer updated = service.updateCustomer(id, newEmail, newPhone);
                            System.out.println("✅ Updated customer: " + updated);
                            break;

                        case 4:
                            System.out.print("Enter Customer ID to delete: ");
                            int delId = sc.nextInt();
                            sc.nextLine();
                            service.deleteCustomer(delId);
                            System.out.println("✅ Customer deleted.");
                            break;

                        case 5:
                            System.out.println("👋 Exiting... Goodbye!");
                            return;

                        default:
                            System.out.println("❌ Invalid option! Please enter between 1 and 5.");
                    }
                } catch (InvalidInputException e) {
                    System.out.println("❌ Input Error: " + e.getMessage());
                } catch (CustomerNotFoundException e) {
                    System.out.println("❌ " + e.getMessage());
                } catch (DataAccessException e) {
                    System.out.println("❌ Database error: " + e.getMessage());
                } catch (Exception e) {
                    System.out.println("⚠️ Unexpected error: " + e.getMessage());
                }
            }
        } finally {
            sc.close();
        }
    }

    // Validation logic
    private static void validateInput(String name, String email, String phone) throws InvalidInputException {
        if (name == null || name.isEmpty()) {
            throw new InvalidInputException("Name cannot be empty!");
        }
        if (email == null || !email.contains("@") || !email.contains(".")) {
            throw new InvalidInputException("Invalid email format!");
        }
        if (phone == null || !phone.matches("\\d{10}")) {
            throw new InvalidInputException("Phone must be 10 digits!");
        }
    }
}

