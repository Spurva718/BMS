package com.bank.repository;

import com.bank.entity.Customer;
import com.bank.exception.CustomerNotFoundException;
import com.bank.exception.DataAccessException;
import com.bank.util.ConnectionUtil;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class CustomerRepository {

    public Customer insertCustomer(Customer customer) throws DataAccessException {
        String sql = "INSERT INTO customers (name, email, phone) VALUES (?, ?, ?) RETURNING customer_id, account_id";
        Connection con = null;
        PreparedStatement pstmt = null;
        ResultSet rs = null;

        try {
            con = ConnectionUtil.getConnection();
            pstmt = con.prepareStatement(sql);
            pstmt.setString(1, customer.getName());
            pstmt.setString(2, customer.getEmail());
            pstmt.setString(3, customer.getPhone());

            rs = pstmt.executeQuery();
            if (rs.next()) {
                customer.setCustomerId(rs.getInt("customer_id"));
                customer.setAccountId(rs.getInt("account_id"));
            }
            return customer;
        } catch (SQLException e) {
            throw new DataAccessException("Error inserting customer", e);
        } finally {
            try { if (rs != null) rs.close(); } catch (SQLException ignored) {}
            try { if (pstmt != null) pstmt.close(); } catch (SQLException ignored) {}
            try { if (con != null) con.close(); } catch (SQLException ignored) {}
        }
    }

    public List<Customer> getAllCustomers() throws DataAccessException {
        List<Customer> list = new ArrayList<>();
        String sql = "SELECT * FROM customers";
        Connection con = null;
        Statement stmt = null;
        ResultSet rs = null;

        try {
            con = ConnectionUtil.getConnection();
            stmt = con.createStatement();
            rs = stmt.executeQuery(sql);

            while (rs.next()) {
                Customer c = new Customer(
                        rs.getString("name"),
                        rs.getString("email"),
                        rs.getString("phone")
                );
                c.setCustomerId(rs.getInt("customer_id"));
                c.setAccountId(rs.getInt("account_id"));
                list.add(c);
            }
            return list;
        } catch (SQLException e) {
            throw new DataAccessException("Error fetching customers", e);
        } finally {
            try { if (rs != null) rs.close(); } catch (SQLException ignored) {}
            try { if (stmt != null) stmt.close(); } catch (SQLException ignored) {}
            try { if (con != null) con.close(); } catch (SQLException ignored) {}
        }
    }

    public Customer updateCustomer(int id, String newEmail, String newPhone) throws DataAccessException, CustomerNotFoundException {
        String sql = "UPDATE customers SET email=?, phone=? WHERE customer_id=? RETURNING *";
        Connection con = null;
        PreparedStatement pstmt = null;
        ResultSet rs = null;

        try {
            con = ConnectionUtil.getConnection();
            pstmt = con.prepareStatement(sql);
            pstmt.setString(1, newEmail);
            pstmt.setString(2, newPhone);
            pstmt.setInt(3, id);
            rs = pstmt.executeQuery();

            if (rs.next()) {
                Customer c = new Customer(
                        rs.getString("name"),
                        rs.getString("email"),
                        rs.getString("phone")
                );
                c.setCustomerId(rs.getInt("customer_id"));
                c.setAccountId(rs.getInt("account_id"));
                return c;
            } else {
                throw new CustomerNotFoundException("Customer with ID " + id + " not found.");
            }
        } catch (SQLException e) {
            throw new DataAccessException("Error updating customer", e);
        } finally {
            try { if (rs != null) rs.close(); } catch (SQLException ignored) {}
            try { if (pstmt != null) pstmt.close(); } catch (SQLException ignored) {}
            try { if (con != null) con.close(); } catch (SQLException ignored) {}
        }
    }

    public void deleteCustomer(int id) throws DataAccessException, CustomerNotFoundException {
        String sql = "DELETE FROM customers WHERE customer_id=?";
        Connection con = null;
        PreparedStatement pstmt = null;

        try {
            con = ConnectionUtil.getConnection();
            pstmt = con.prepareStatement(sql);
            pstmt.setInt(1, id);

            int rows = pstmt.executeUpdate();
            if (rows == 0) {
                throw new CustomerNotFoundException("Customer with ID " + id + " not found.");
            }
        } catch (SQLException e) {
            throw new DataAccessException("Error deleting customer", e);
        } finally {
            try { if (pstmt != null) pstmt.close(); } catch (SQLException ignored) {}
            try { if (con != null) con.close(); } catch (SQLException ignored) {}
        }
    }
}

